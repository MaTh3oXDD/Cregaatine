# -*- coding: utf-8 -*-
"""Un-lazy the mirrored pages.

The live site used WP Smush's lazy-loader: every <img> ships a 1x1 base64 SVG
in src= and the real file in data-src=, with a JS library swapping them in.
That library never initialises in this static mirror (its inline config is
generated by WordPress at runtime and isn't part of the saved HTML), so ~49 of
58 images on the homepage stayed as blank placeholders forever.

Rather than patch a third-party minified lazy-loader, promote the real URLs
into the real attributes and let the browser's own native lazy-loading handle
deferral. Same performance benefit, no JS dependency.
"""
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(ROOT, "site")

IMG_RE = re.compile(r"<img\b[^>]*>", re.IGNORECASE)
PLACEHOLDER_SRC_RE = re.compile(
    r'\ssrc="data:image/svg\+xml;base64,[^"]*"', re.IGNORECASE
)


def fix_img(tag):
    if "data-src=" not in tag:
        return tag
    # drop the 1x1 placeholder so the promoted data-src can take the src slot
    tag = PLACEHOLDER_SRC_RE.sub("", tag)
    tag = re.sub(r"\sdata-src=", " src=", tag, count=1)
    tag = re.sub(r"\sdata-srcset=", " srcset=", tag, count=1)
    tag = re.sub(r"\sdata-sizes=", " sizes=", tag, count=1)
    # native deferral replaces the JS library
    if "loading=" not in tag:
        tag = tag.replace("<img", '<img loading="lazy"', 1)
    # the placeholder-sizing custom properties are meaningless now and their
    # aspect-ratio var can squash the real image
    tag = re.sub(r'\sstyle="--smush-placeholder-[^"]*"', "", tag)
    tag = tag.replace(" lazyload", "")
    return tag


total_files = 0
total_imgs = 0
for dirpath, dirnames, filenames in os.walk(SITE):
    if "assets" in dirpath.split(os.sep):
        continue
    for fn in filenames:
        if not fn.endswith(".html"):
            continue
        path = os.path.join(dirpath, fn)
        html = open(path, encoding="utf-8").read()
        count = [0]

        def repl(m):
            before = m.group(0)
            after = fix_img(before)
            if after != before:
                count[0] += 1
            return after

        new_html = IMG_RE.sub(repl, html)
        if count[0]:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new_html)
            total_files += 1
            total_imgs += count[0]
            print("unlazied %3d images: %s" % (count[0], os.path.relpath(path, SITE)))

print("---")
print("files updated:", total_files, "| images fixed:", total_imgs)
